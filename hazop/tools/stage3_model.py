def build_catalog(res):
    """経路ごとに適用可能な対策インスタンス（テンプレート×ゾーン）を求める"""
    inst = OrderedDict()   # (key, zone) -> dict

    def get(key, zone, **kw):
        k = (key, zone)
        if k not in inst:
            inst[k] = dict(key=key, zone=zone, paths=set(), results=set(), causes=set(), groups=set(), **kw)
        return inst[k]

    for r in res.values():
        for p in r["paths"]:
            p["app"] = []      # (inst_key, credited(bool), note)
            # 原因発生防止
            for c in p["causes"]:
                for (key, name, kind, cls, f, rx, ini, ann, pos, why) in CAUSE_T:
                    if re.search(rx, c["text"]) and not (key in EXCL and re.search(EXCL[key], c["text"])):
                        cz = 0 if key in ZONE0 else c["zone"]
                        m = get(key, cz, name=name, kind=kind, cls=cls, f=f, ini=ini, ann=ann, pos=pos, why=why)
                        m["causes"].add(c["id"])
                        p["app"].append(((key, cz), True, f"{c['id']}の発生を防止"))
            # 伝播遮断（SIS等）
            for (key, zone, name, f, specs, ini, ann, pos) in SIS:
                for sp in specs:
                    g, crx = (sp, None) if isinstance(sp, str) else sp
                    if p["group"] != g:
                        continue
                    if crx and not any(re.search(crx, c["text"]) for c in p["causes"]):
                        continue
                    m = get(key, zone, name=name, kind="伝播遮断", cls=SIS_CLS.get(key, f"SIS-Z{zone}"), f=f, ini=ini, ann=ann, pos=pos,
                            why=("IEC 61511のSIL2相当（PFDavg 1E-2〜1E-3）を想定し1/100。専用センサー・専用遮断弁・BPCSと独立したロジックを前提（SIL検証は要確認）"
                                 if f == 1 / 100 else "SIL1相当（PFDavg 1E-1〜1E-2）を想定し1/10（演習仮定）"))
                    m["groups"].add(g)
                    if any(COMMON_UTIL.search(c["text"]) for c in p["causes"]):
                        p["app"].append(((key, zone), False, "要確認：原因（計装空気・電源喪失）とSISの遮断弁・電源が共通依存の可能性があり頻度計算から除外"))
                    else:
                        p["app"].append(((key, zone), True, f"{g}の偏差位置で遮断"))
                    break
            for k_, cred, _ in p["app"]:
                if cred:
                    inst[k_]["paths"].add(p["pid"])
                    inst[k_]["results"].add(r["id"])
    for (key, name, kind, zones, ini, ann, pos, why) in MITIG:
        for z in zones:
            get(key, z, name=name, kind=kind, cls="—", f=None, ini=ini, ann=ann, pos=pos, why=why)
    return inst


def path_factor(app_keys, inst):
    """採用済み対策（適用・クレジット可）から経路の残余倍率を計算。
    同一独立性クラス（同一センサー・遮断弁・ロジック・運転班・保全活動に依存）の対策は積をとらず、
    単一の効果のみをクレジットする（追加採用で計算上のリスクが増える逆転を避けるため、採用済みのうち1件の効果）"""
    bycls = defaultdict(list)
    for k in app_keys:
        bycls[inst[k]["cls"]].append(inst[k]["f"])
    f = 1.0
    for v in bycls.values():
        f *= min(v)
    return f


def best_factor(p, inst):
    """全候補を採用した場合に到達しうる最小の倍率（同一クラスは最良の単一効果）"""
    bycls = defaultdict(list)
    for k, cred, _ in p["app"]:
        if cred:
            bycls[inst[k]["cls"]].append(inst[k]["f"])
    f = 1.0
    for v in bycls.values():
        f *= min(v)
    return f
