def load_stage2(path):
    wb = load_workbook(path, data_only=True, read_only=True)
    ws = wb["04_結果―原因_AND_ORツリー"]
    res = OrderedDict()
    for row in ws.iter_rows(min_row=5, values_only=True):
        if row[0] is None:
            continue
        rid = row[27]
        if rid not in res:
            res[rid] = dict(no=row[0], id=rid, text=row[1], zone=row[2], D=row[3], S=row[4], kinds=row[5], G=row[6], paths=[])
        if row[28] is None:      # 原因未確定
            res[rid]["undetermined"] = True
            continue
        causes = []
        for k in range(3):
            t = row[8 + 3 * k]
            if t:
                cid, ctext = t.split("｜", 1)
                z = int(row[9 + 3 * k][1])
                causes.append(dict(id=cid, text=ctext, zone=z, freq=row[10 + 3 * k]))
        res[rid]["paths"].append(dict(pid=row[28], H=row[7], causes=causes, route=row[17], inter=row[18], conds=row[19], cp=row[20],
                                      indep=row[21], flags=row[25] or "", group=row[18].split(" ")[0], s2ref=row[23]))
    return res


