GROUPS = []
_cnt = {}


def R(text, *cats):
    return (text, set(cats))


def G(z, equip, target, gw, causes, results, keys=()):
    _cnt[z] = _cnt.get(z, 0) + 1
    GROUPS.append(dict(id=f"Z{z}-{_cnt[z]:02d}", zone=ZN[z], z=z, equip=equip, target=target,
                       gw=gw, causes=list(causes), results=list(results), keys=set(keys) | {f"Z{z}"}))


