def ladder(loc, fluid, liquid=False, h2=False, vessel=None, big=False, env=True):
    o = []
    o.append(R(f"{loc}から{fluid}が外部へ漏洩し、大気中に放出される", "LEAK"))
    if liquid:
        o.append(R(f"{loc}から液化C4が大量に流出し、フラッシュ蒸発により大規模な可燃性蒸気雲が形成される", "LEAK"))
    o.append(R(f"{loc}からの放出が即時着火し、噴流火災により周辺の機器・配管・ケーブルが損傷する", "FIRE"))
    if h2:
        o.append(R(f"{loc}の漏洩ガスは水素を含み着火エネルギーが小さいため即時着火しやすく、視認しにくい水素火炎により周辺機器が損傷する", "FIRE"))
    o.append(R(f"{loc}からの放出ガス雲が着火し、フラッシュ火災によりガス雲範囲内の機器・計装ケーブルが焼損する", "FIRE"))
    if liquid:
        o.append(R(f"{loc}から流出した液が地表・ピットに滞留して着火し、プール火災の火炎輻射で周辺機器・架構が損傷する", "FIRE"))
    o.append(R(f"{loc}からの放出ガス雲が遅延着火して蒸気雲爆発が発生し、爆風により周辺設備・隣接設備が破壊される", "VCE"))
    o.append(R(f"{loc}起因の蒸気雲爆発の爆風・飛来物により、複数のオンサイト作業員が死亡・重傷を負う（在場人数・滞留域により成立）", "VCE", "MD"))
    if big:
        o.append(R(f"{loc}起因の爆風で近傍の計器室・仮設事務所等が損壊し、屋内の複数人員が死亡・重傷を負う（建屋配置は実機確認が必要）", "VCE", "MD"))
    o.append(R(f"{loc}の火災（噴流火災・フラッシュ火災）に近傍の作業員1名が巻き込まれ、死亡・重度熱傷を負う", "SD"))
    if vessel:
        o.append(R(f"火災曝露により{vessel}が加熱・強度低下して破裂し、火球またはBLEVE相当の事象へ拡大する", "ESC"))
    o.append(R(f"{loc}の火炎が隣接する配管・容器・架構に衝突・輻射し、二次破裂・延焼による連鎖損傷が発生する", "ESC"))
    if big:
        o.append(R(f"{loc}起因の爆発・火災・煙が構外に及び、周辺住民の屋内退避・避難が必要となる（規模・距離により成立）", "OFF"))
    o.append(R(f"{loc}起因の火災・爆発による設備損壊でプラントが長期操業停止し、復旧費用・逸失利益が発生する", "BIZ"))
    if env and liquid:
        o.append(R(f"{loc}から流出した液炭化水素・油分が側溝・排水系へ流入し、土壌・公共水域が汚染される", "ENV"))
    if env:
        o.append(R(f"{loc}の火災の消火で生じた炭化水素含有の消火排水が排水系・水域へ流出し、環境汚染が発生する", "ENV"))
        o.append(R(f"{loc}から未燃の炭化水素（VOC）が大気へ排出され、大気環境汚染・排出規制違反となる", "ENVV"))
    return o


def relief(src, liquid=False):
    o = [R(f"{src}の過圧により安全弁等の放圧装置が作動し、大量の可燃性C4が閉鎖ガス処理系へ放出される（放圧装置の設置・放出先は実機確認が必要な候補）", "RELIEF"),
         R("閉鎖ガス処理系の受入能力を超え、ヘッダ背圧上昇により同ヘッダに接続する他系統の放圧能力も低下する（受入能力は実機確認が必要）", "RELIEF")]
    if liquid:
        o += [R(f"{src}から液を伴う放出となり、閉鎖ガス処理系の気液分離設備から液が溢流する（設備構成は実機確認が必要な候補）", "RELIEF"),
              R("燃焼設備へ液が持ち込まれ、燃焼液滴の降下（火の雨）により周辺で火災が発生する（フレア等燃焼設備の有無は実機確認が必要な候補）", "RELIEF", "FIRE")]
    o += [R("放出先の能力不足・不全により可燃性ガスが大気へ直接放出され、地表付近に蒸気雲が滞留する", "RELIEF", "LEAK"),
          R("大気放出された蒸気雲が遅延着火し、蒸気雲爆発により放出点周辺の設備が破壊される", "RELIEF", "VCE"),
          R("放出点周辺の蒸気雲爆発により、複数のオンサイト作業員が死亡・重傷を負う（在場人数により成立）", "RELIEF", "VCE", "MD"),
          R("大量の未燃炭化水素・黒煙が大気へ排出され、大気環境汚染・近隣苦情・規制違反となる", "ENVV")]
    return o


def rupture(vessel):
    return [R(f"放圧が不足・不全の場合、{vessel}が設計圧力を超えて破裂し、内容物が瞬時に大量放出される（設計圧力は実機確認が必要）", "LEAK"),
            R(f"{vessel}の破裂による圧力波・破片飛散で隣接機器・配管が損傷する", "ESC"),
            R(f"{vessel}の破裂破片・圧力波により近傍の作業員が死亡・重傷を負う", "SD")]


def biz(text):
    return R(text, "BIZ")


